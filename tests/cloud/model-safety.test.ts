test('worker persists call/tool counts and digest receipts; no-op output produces no recursive work', async () => {
    await h.create();
    const job = (await queue.claim())!;
    expect(job).not.toBeNull();
    const context = await queue.context(job);
    let count = 0;
    const adapter: c.NemotronAdapter = { probe: async () => { throw new Error('not live'); }, next: async () => count++ === 0 ? { type: 'tool_calls', calls: [{ id: 'r1', name: 'read_project_state', arguments: {} }] } : { type: 'proposal', proposal: make(job, context.snapshot) } };
    await runJob(queue, adapter, job, new AbortController().signal);
    const row = (await h.pool.query('SELECT * FROM jobs')).rows[0];
    expect(row.state).toBe('completed');
    expect(row.data).toMatchObject({ modelCalls: 2, toolCalls: 1 });
    expect(row.tool_receipts[0]).toMatchObject({ name: 'read_project_state', resultDigest: expect.stringMatching(/^[a-f0-9]{64}$/) });
    expect((await h.pool.query('SELECT 1 FROM jobs')).rowCount).toBe(1);
});
test('owner override survives a later model edit and generated completion cannot claim owner authority', async () => {
    const { projectId } = await h.create();
    const job = (await queue.claim())!;
    const context = await queue.context(job);
    const p = make(job, context.snapshot);
    const taskId = randomUUID();
    p.taskChanges = [{ type: 'create', task: { id: taskId, title: 'Owner-controlled task', status: 'todo', requirementOrigin: 'brief', evidenceLevel: 'none', evidenceIds: [] } }];
    await queue.commit(job, p);
    const snapshot = (await h.request('GET', `/v1/projects/${projectId}/snapshot`)).json();
    await h.request('POST', `/v1/projects/${projectId}/actions`, command({ type: 'update_task', taskId, status: 'in_progress' }, snapshot.project.revision));
    const current = (await h.request('GET', `/v1/projects/${projectId}/snapshot`)).json();
    const synthetic = { ...job, baseProjectRevision: current.project.revision };
    const edit = make(synthetic, current);
    edit.taskChanges = [{ type: 'update', taskId, expectedRevision: 1, status: 'todo', evidenceLevel: 'none', evidenceIds: [] }];
    expect(() => validateProposal(edit, synthetic, { snapshot: current, grantVersions: [] })).toThrow('proposal_owner_override');
    const completion = make(synthetic, current);
    completion.taskChanges = [{ type: 'create', task: { id: randomUUID(), title: 'Unsupported completion', status: 'done', requirementOrigin: 'model_suggestion', evidenceLevel: 'none', evidenceIds: [] } }];
    expect(() => validateProposal(completion, synthetic, { snapshot: current, grantVersions: [] })).toThrow('proposal_completion_authority');
});
