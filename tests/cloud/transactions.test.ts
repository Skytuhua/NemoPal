import { randomUUID } from 'node:crypto';
import { afterEach, beforeEach, expect, test } from 'vitest';
import * as c from '@living-playbooks/contracts';
import { issueGrant, redeem, digest } from '../../apps/cloud/src/auth/credentials';
import { buildServer } from '../../apps/cloud/src/api/server';
import { command, setup } from './helpers';
let h: Awaited<ReturnType<typeof setup>>;
beforeEach(async () => { h = await setup(); });
afterEach(async () => { await h?.close(); });
test('duplicate observation IDs in one batch reject atomically instead of acknowledging the same ID twice',async()=>{
  const {projectId}=await h.create();
  const source=(await h.request('POST',`/v1/projects/${projectId}/sources`,command({sourceKey:'duplicate-batch',adapterId:'synthetic',adapterVersion:'1',capability:'history_only',exportPolicy:'metadata_only'},0))).json().result;
  const observation={id:randomUUID(),bindingId:source.id,grantRevision:0,sourceItemId:'item',sourceRevision:'1',kind:'activity',occurredAt:new Date().toISOString(),observedAt:new Date().toISOString(),metadata:{type:'activity',state:'active'},provenance:{adapterId:'synthetic',adapterVersion:'1',mode:'fixture',evidenceLevel:'none'}};
  expect((await h.request('POST',`/v1/sources/${source.id}/observations`,command({observations:[observation,observation]}))).statusCode).toBe(422);
  expect((await h.pool.query('SELECT 1 FROM observations')).rowCount).toBe(0);
});
test('pairing is single use under concurrency, expires, and revoked credentials deny reads', async () => {
    const g = await issueGrant(h.pool, { ownerId: h.ownerId, timezone: 'UTC' });
    const results = await Promise.allSettled([redeem(h.pool, g.code), redeem(h.pool, g.code)]);
    expect(results.filter(r => r.status === 'fulfilled')).toHaveLength(1);
    const expired = await issueGrant(h.pool, { ownerId: h.ownerId, timezone: 'UTC' }, new Date(Date.now() - 700000));
    await expect(redeem(h.pool, expired.code)).rejects.toMatchObject({ status: 401 });
    expect((await h.pool.query('SELECT 1 FROM credentials WHERE secret_hash=$1', [h.auth.token])).rowCount).toBe(0);
    await h.pool.query('UPDATE credentials SET revoked_at=now() WHERE secret_hash=$1', [digest(h.auth.token)]);
    expect((await h.request('GET', '/v1/projects')).statusCode).toBe(401);
});
test('concurrent replay persists one project, job and receipt; changed payload conflicts; restart retains snapshot', async () => {
    const body = command({ title: 'Replay', brief: 'Synthetic brief' });
    const [a, b] = await Promise.all([h.request('POST', '/v1/projects', body), h.request('POST', '/v1/projects', body)]);
    expect(a.statusCode).toBe(200);
    expect(b.json()).toEqual(a.json());
    expect(a.json().receipt.requestHash).toBe(await c.hashCommand('/v1/projects', c.commandEnvelopeSchema(c.CreateProjectInputSchema).parse(body)));
    expect((await h.pool.query('SELECT 1 FROM projects')).rowCount).toBe(1);
    expect((await h.pool.query('SELECT 1 FROM jobs')).rowCount).toBe(1);
    expect((await h.request('POST', '/v1/projects', { ...body, input: { title: 'changed', brief: 'Synthetic brief' } })).statusCode).toBe(409);
    const id = (await h.pool.query('SELECT id FROM projects')).rows[0].id;
    const old = (await h.request('GET', `/v1/projects/${id}/snapshot`)).json();
    expect(c.ProjectSnapshotSchema.safeParse(old).success).toBe(true);
    expect(old.connection.inference.available).toBe(false);
    const restarted = buildServer(h.pool);
    const response = await restarted.inject({ method: 'GET', url: `/v1/projects/${id}/snapshot`, headers: { authorization: `Bearer ${h.auth.token}` } });
    expect(response.json()).toEqual(old);
    await restarted.close();
});
test('cross-owner and cross-device source operations expose no foreign content', async () => {
    const { projectId } = await h.create();
    const g = await issueGrant(h.pool, { timezone: 'UTC' });
    const other = await redeem(h.pool, g.code);
    expect((await h.request('GET', `/v1/projects/${projectId}/snapshot`, undefined, other.token)).statusCode).toBe(404);
    expect((await h.request('POST', `/v1/projects/${projectId}/actions`, command({ type: 'accept_plan' }, 0), other.token)).statusCode).toBe(404);
    const source = (await h.request('POST', `/v1/projects/${projectId}/sources`, command({ sourceKey: 'synthetic', adapterId: 'codex', adapterVersion: '1', capability: 'incremental_history', exportPolicy: 'approved_excerpts' }, 0))).json().result;
    const another = await redeem(h.pool, (await issueGrant(h.pool, { ownerId: h.ownerId, timezone: 'UTC' })).code);
    expect((await h.request('POST', `/v1/sources/${source.id}/health`, command({ grantRevision: 0, state: 'following', capability: 'incremental_history', lastObservedAt: null, errorClass: null }), another.token)).statusCode).toBe(404);
});
test('ingestion deduplicates source versions, rejects paused/revoked queues and metadata excerpts, health creates no inference', async () => {
    const { projectId } = await h.create();
    const source = (await h.request('POST', `/v1/projects/${projectId}/sources`, command({ sourceKey: 'synthetic', adapterId: 'codex', adapterVersion: '1', capability: 'incremental_history', exportPolicy: 'approved_excerpts' }, 0))).json().result;
    const observation = { id: randomUUID(), bindingId: source.id, grantRevision: 0, sourceItemId: 'm1', sourceRevision: 'v1', kind: 'assistant_report', occurredAt: new Date().toISOString(), observedAt: new Date().toISOString(), excerpt: 'Synthetic private-safe report', metadata: { type: 'message', role: 'assistant' }, provenance: { adapterId: 'codex', adapterVersion: '1', mode: 'fixture', evidenceLevel: 'agent_reported' } };
    const ingest = () => h.request('POST', `/v1/sources/${source.id}/observations`, command({ observations: [observation] }));
    expect((await ingest()).json().result.acceptedIds).toEqual([observation.id]);
    expect((await ingest()).json().result.duplicateIds).toEqual([observation.id]);
    const jobs = (await h.pool.query('SELECT 1 FROM jobs')).rowCount;
    expect((await h.request('POST', `/v1/sources/${source.id}/health`, command({ grantRevision: 0, state: 'following', capability: 'incremental_history', lastObservedAt: new Date().toISOString(), errorClass: null }))).statusCode).toBe(200);
    expect((await h.pool.query('SELECT 1 FROM jobs')).rowCount).toBe(jobs);
    expect((await h.request('POST', `/v1/sources/${source.id}/state`, command({ state: 'paused', grantRevision: 0 }))).statusCode).toBe(200);
    expect((await ingest()).statusCode).toBe(409);
    expect((await h.request('POST', `/v1/sources/${source.id}/revoke`, command({ grantRevision: 0, removeExcerpts: true }))).statusCode).toBe(200);
    expect((await ingest()).statusCode).toBe(409);
    expect((await h.pool.query('SELECT data FROM observations')).rows.every(row => row.data === null)).toBe(true);
});
test('draft saves use independent revision, deletion fences jobs and retains non-content replay tombstones', async () => {
    const { projectId } = await h.create();
    const documentId = randomUUID();
    const saved = await h.request('PUT', `/v1/projects/${projectId}/documents/${documentId}`, command({ text: 'Owner draft' }, 0));
    expect(saved.statusCode).toBe(200);
    expect(saved.json().result.revision).toBe(1);
    expect((await h.request('PUT', `/v1/projects/${projectId}/documents/${documentId}`, command({ text: 'stale' }, 0))).statusCode).toBe(409);
    const snapshot = (await h.request('GET', `/v1/projects/${projectId}/snapshot`)).json();
    const deletion = command({}, snapshot.project.revision);
    expect((await h.request('DELETE', `/v1/projects/${projectId}`, deletion)).json().result).toBeNull();
    expect((await h.request('DELETE', `/v1/projects/${projectId}`, deletion)).statusCode).toBe(200);
    expect((await h.request('GET', `/v1/projects/${projectId}/snapshot`)).statusCode).toBe(404);
    expect((await h.pool.query('SELECT state FROM jobs')).rows.every(j => j.state === 'cancelled')).toBe(true);
    expect((await h.pool.query('SELECT data FROM projects')).rows[0].data).toBeNull();
    expect((await h.pool.query('SELECT 1 FROM documents')).rowCount).toBe(0);
    expect(JSON.stringify((await h.pool.query('SELECT response FROM command_receipts')).rows)).not.toContain('Owner draft');
});
